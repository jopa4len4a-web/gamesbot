function randomItem(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

function generatePlayer(userId, username) {
  return {
    userId,
    username: username || `Игрок_${userId}`,
    alive: true,
    profession: randomItem(professions),
    health: randomItem(health),
    hobby: randomItem(hobbies),
    luggage: randomItem(luggage),
    fact: randomItem(facts),
    votes: 0,
    revealed: [] // какие характеристики уже раскрыты
  };
}

